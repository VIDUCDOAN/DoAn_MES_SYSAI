-- Mốc 1: tài khoản, quyền FUN, sản phẩm và audit. Chưa tạo bảng sản xuất khi chưa triển khai luồng đó.
IF OBJECT_ID(N'dbo.SYS_USER', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SYS_USER (
        Id INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_SYS_USER PRIMARY KEY,
        Username NVARCHAR(50) NOT NULL CONSTRAINT UQ_SYS_USER_Username UNIQUE,
        PasswordHash NVARCHAR(600) NOT NULL,
        FullName NVARCHAR(200) NOT NULL,
        IsActive BIT NOT NULL CONSTRAINT DF_SYS_USER_IsActive DEFAULT 1,
        SessionVersion INT NOT NULL CONSTRAINT DF_SYS_USER_SessionVersion DEFAULT 1,
        CONSTRAINT CK_SYS_USER_SessionVersion CHECK (SessionVersion > 0)
    );
END;
GO
IF OBJECT_ID(N'dbo.SYS_FUNCTION', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SYS_FUNCTION (
        FunctionCode VARCHAR(50) NOT NULL CONSTRAINT PK_SYS_FUNCTION PRIMARY KEY,
        FunctionName NVARCHAR(200) NOT NULL
    );
END;
IF OBJECT_ID(N'dbo.SYS_PERMISSION', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SYS_PERMISSION (
        UserId INT NOT NULL CONSTRAINT FK_SYS_PERMISSION_User REFERENCES dbo.SYS_USER(Id),
        FunctionCode VARCHAR(50) NOT NULL CONSTRAINT FK_SYS_PERMISSION_Function REFERENCES dbo.SYS_FUNCTION(FunctionCode),
        CONSTRAINT PK_SYS_PERMISSION PRIMARY KEY (UserId, FunctionCode)
    );
END;
GO
IF OBJECT_ID(N'dbo.M_PRODUCT', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.M_PRODUCT (
        Id INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_M_PRODUCT PRIMARY KEY,
        ModelCode VARCHAR(50) NOT NULL CONSTRAINT UQ_M_PRODUCT_ModelCode UNIQUE,
        ModelName NVARCHAR(200) NOT NULL,
        Description NVARCHAR(1000) NULL,
        IsDeleted BIT NOT NULL CONSTRAINT DF_M_PRODUCT_IsDeleted DEFAULT 0,
        Version INT NOT NULL CONSTRAINT DF_M_PRODUCT_Version DEFAULT 1,
        CreatedAt DATETIME2(7) NOT NULL CONSTRAINT DF_M_PRODUCT_CreatedAt DEFAULT SYSUTCDATETIME(),
        CONSTRAINT CK_M_PRODUCT_Code CHECK (LEN(ModelCode) BETWEEN 2 AND 50 AND ModelCode NOT LIKE '%[^A-Z0-9_-]%' COLLATE Latin1_General_100_BIN2),
        CONSTRAINT CK_M_PRODUCT_Name CHECK (LEN(LTRIM(RTRIM(ModelName))) >= 2),
        CONSTRAINT CK_M_PRODUCT_Version CHECK (Version > 0)
    );
END;
GO
IF OBJECT_ID(N'dbo.SYS_AUDIT_LOG', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SYS_AUDIT_LOG (
        Id BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_SYS_AUDIT_LOG PRIMARY KEY,
        Who NVARCHAR(50) NOT NULL,
        [When] DATETIME2(7) NOT NULL,
        WhereIp NVARCHAR(45) NOT NULL,
        ActionType VARCHAR(20) NOT NULL,
        EntityName VARCHAR(100) NOT NULL,
        EntityId NVARCHAR(100) NOT NULL,
        OldDataJson NVARCHAR(MAX) NULL,
        NewDataJson NVARCHAR(MAX) NULL,
        CorrelationId NVARCHAR(100) NOT NULL,
        CONSTRAINT CK_SYS_AUDIT_LOG_OldJson CHECK (OldDataJson IS NULL OR ISJSON(OldDataJson) = 1),
        CONSTRAINT CK_SYS_AUDIT_LOG_NewJson CHECK (NewDataJson IS NULL OR ISJSON(NewDataJson) = 1)
    );
    CREATE INDEX IX_SYS_AUDIT_LOG_Entity ON dbo.SYS_AUDIT_LOG(EntityName, EntityId, Id DESC);
END;
GO
